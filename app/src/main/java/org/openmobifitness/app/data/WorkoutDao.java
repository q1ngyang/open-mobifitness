package org.openmobifitness.app.data;
import androidx.room.*;
import java.util.List;
@Dao public interface WorkoutDao {
 @Query("SELECT * FROM sessions ORDER BY start DESC") List<SessionRow> sessions();
 @Query("SELECT * FROM sessions ORDER BY startEpoch DESC, id DESC LIMIT 100") List<SessionRow> recentSessions();
 @Query("SELECT * FROM sessions WHERE status='active'") List<SessionRow> activeSessions();
 @RawQuery List<SessionRow> history(androidx.sqlite.db.SupportSQLiteQuery query);
 @Query("UPDATE sessions SET archived=:archived WHERE id=:id AND status!='active'") void setArchived(String id, boolean archived);
 @Query("SELECT * FROM sessions WHERE id=:id") SessionRow session(String id);
 @Query("SELECT * FROM samples ORDER BY sessionId,elapsedMs") List<SampleRow> samples();
 @Query("SELECT * FROM samples WHERE sessionId=:id ORDER BY elapsedMs") List<SampleRow> samplesFor(String id);
 @Query("SELECT * FROM sessions WHERE id>:after ORDER BY id LIMIT :limit") List<SessionRow> sessionPage(String after,int limit);
 @Query("SELECT * FROM samples WHERE (sessionId,elapsedMs)>(:id,:time) ORDER BY sessionId,elapsedMs LIMIT :limit") List<SampleRow> samplePage(String id,long time,int limit);
 @Query("SELECT * FROM samples WHERE sessionId=:id AND elapsedMs=:time") SampleRow sampleAt(String id,long time);
 @Query("SELECT * FROM workouts WHERE id>:after ORDER BY id LIMIT :limit") List<WorkoutRow> workoutPage(String after,int limit);
 @Query("SELECT * FROM workouts WHERE id=:id") WorkoutRow workoutAt(String id);
 @Query("SELECT COUNT(*) FROM sessions") long sessionCount();
 @Query("SELECT COUNT(*) FROM samples") long sampleCount();
 @Query("SELECT COUNT(*) FROM workouts") long workoutCount();
 @Query("SELECT * FROM preference_restore WHERE id=1") PreferenceRestoreRow pendingPreferences();
 @Upsert void pendingPreferences(PreferenceRestoreRow row);
 @Query("DELETE FROM preference_restore") void clearPendingPreferences();
 @Query("SELECT * FROM workouts ORDER BY id") List<WorkoutRow> workouts();
 @Upsert void session(SessionRow row);
 @Insert(onConflict=OnConflictStrategy.ABORT) void sample(SampleRow row);
 @Insert(onConflict=OnConflictStrategy.ABORT) void samples(List<SampleRow> rows);
 @Upsert void workout(WorkoutRow row);
 @Query("DELETE FROM sessions WHERE id=:id") void deleteSession(String id);
 @Query("DELETE FROM workouts WHERE id=:id") void deleteWorkout(String id);
}
